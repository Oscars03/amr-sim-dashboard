"""A robot whose URDF sets no sim-fidelity knob runs exactly as amr-sim-dashboard main 96efcfa.

The goldens (test/data/default_trace_*.json.gz) were generated by test/default_trace.py from a
clean export of 96efcfa, before the knobs existed. Every recorded output -- pose, /odom,
/imu, odom->base_link TF, /scan digest, encoder, /wheel/vel, /joint_states, /collision --
must match value for value (==, no tolerance), and so must the 'Loaded config from URDF'
line that master-ackerman-thesis scripts/a4_campaign_runs.sh config_ok() greps.

    cd simamr_ws/src/amr_2dsim && python3 -m pytest test/test_default_invariance.py
"""
import pytest

import default_trace as D

# a4_campaign_runs.sh:49 (master-ackerman-thesis 04371ea), the default EXPECT_CONFIG.
EXPECT_CONFIG = ('model=ackermann|max_steer=18.0°|steer_backlash=3.22°|steer_zero_offset=-0.43°|'
                 'drive_resp=on g_fast=0.557,tau_fast=0.01,g_slow=0.374,tau_slow=7.77,accel=3.81|'
                 'steer_latency=0.05s')

# Every knob away from its default, for the "the Loaded config line does not move" check.
ALL_KNOBS_ON = ('<odom_lin_scale>1.029</odom_lin_scale><odom_yaw_scale>1.271</odom_yaw_scale>'
                '<odom_lin_noise_std>0.01</odom_lin_noise_std>'
                '<odom_yaw_noise_std>0.01</odom_yaw_noise_std>'
                '<imu_omega_source>achieved</imu_omega_source>'
                '<imu_gyro_noise_std>0.005</imu_gyro_noise_std><imu_gyro_bias>0.002</imu_gyro_bias>'
                '<slip_long>0.05</slip_long><slip_yaw>0.1</slip_yaw>'
                '<understeer_gradient>0.2</understeer_gradient><yaw_rate_tau>0.1</yaw_rate_tau>'
                '<drive_latency>0.05</drive_latency><noise_seed>42</noise_seed>')


def config_ok(log_lines, expect=EXPECT_CONFIG):
    """a4_campaign_runs.sh config_ok(): the FIRST line with 'Loaded config from URDF' must
    contain every '|'-separated piece."""
    line = D.loaded_config_line(log_lines)
    return line is not None and all(piece in line for piece in expect.split('|'))


def first_difference(a, b):
    for i, (x, y) in enumerate(zip(a, b)):
        if x != y:
            return i, x, y
    return (min(len(a), len(b)), 'length', (len(a), len(b))) if len(a) != len(b) else None


@pytest.mark.parametrize('variant', list(D.VARIANTS))
def test_every_output_is_identical_to_main(variant):
    golden = D.load_golden(variant)
    now = D.golden_record(variant)
    assert now['loaded_config_line'] == golden['loaded_config_line']
    for key, want in golden.items():
        if key == 'loaded_config_line':
            continue
        diff = first_difference(now[key], want)
        assert diff is None, f'{variant} {key}: first difference at tick {diff[0]}: {diff[1]} != {diff[2]}'


@pytest.mark.parametrize('variant', list(D.VARIANTS))
def test_ground_truth_equals_odom_while_every_knob_is_off(variant):
    out, _ = D.run_trace(variant)
    assert len(out['ground_truth']) == len(out['odom'])
    for gt, od in zip(out['ground_truth'], out['odom']):
        assert gt['frame'] == 'map' and od['frame'] == 'odom'
        assert gt['pos'] == od['pos'] and gt['q'] == od['q']
        assert gt['ang'] == od['ang'] and gt['lin'][0] == od['lin'][0]


def test_the_harness_still_accepts_the_a4_build():
    """rhino_a4 is the build a4_campaign_runs.sh runs: its EXPECT_CONFIG still matches."""
    out, _ = D.run_trace('rhino_a4')
    assert config_ok(out['log'])
    assert D.loaded_config_line(out['log']) == D.load_golden('rhino_a4')['loaded_config_line']


def test_new_knobs_never_touch_the_loaded_config_line():
    """Even with every knob on, the 'Loaded config from URDF' line is byte-identical; the
    knobs go on their own 'Sim fidelity config:' line, after it, which config_ok never reads."""
    out, _ = D.run_trace('rhino_a4', tags=ALL_KNOBS_ON)
    golden_line = D.load_golden('rhino_a4')['loaded_config_line']
    assert D.loaded_config_line(out['log']) == golden_line
    assert config_ok(out['log'])
    fid = [line for line in out['log'] if line.startswith('Sim fidelity config:')]
    assert len(fid) == 1
    assert 'Loaded config from URDF' not in fid[0]
    assert out['log'].index(golden_line) < out['log'].index(fid[0])
    for piece in ('odom_lin_scale=1.029', 'odom_yaw_scale=1.271', 'imu_omega_source=achieved',
                  'slip_yaw=0.1', 'understeer_gradient=0.2', 'yaw_rate_tau=0.1s',
                  'drive_latency=0.05s', 'noise_seed=42 (urdf)'):
        assert piece in fid[0]


def test_the_fidelity_line_reports_defaults_and_an_auto_seed():
    out, node = D.run_trace('rhino')
    fid = [line for line in out['log'] if line.startswith('Sim fidelity config:')]
    assert len(fid) == 1
    assert fid[0].startswith('Sim fidelity config: odom_lin_scale=1 odom_yaw_scale=1 '
                             'odom_lin_noise_std=0 odom_yaw_noise_std=0 imu_omega_source=command '
                             'imu_gyro_noise_std=0 imu_gyro_bias=0 slip_long=0 slip_yaw=0 '
                             'understeer_gradient=0 yaw_rate_tau=0s drive_latency=0s noise_seed=')
    assert fid[0].endswith(f'noise_seed={node.noise_seed} (auto)')
